import { existsSync, readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";

import { ROOT, note, check, readOrEmpty, stripComments } from "./lib.mjs";
import { handlerListBlock, tsSourceFiles } from "./sources.mjs";

// `build.rs` lists every command for the app ACL manifest. A command missing
// there has no permission to grant, so every window's invoke of it is refused;
// one missing here was deleted from the app and still has a grant.
console.log("\n[ App ACL manifest — build.rs APP_COMMANDS ↔ generate_handler! ]");
{
  // Trailing `//` comments too: one sits after `simulate_hue_fault,`.
  const registered = handlerListBlock
    .replace(/\/\/[^\n]*/g, "")
    .split(",")
    .map((entry) => entry.trim())
    .filter(Boolean);
  const buildSource = readOrEmpty(resolve(ROOT, "src-tauri/build.rs"), "rust build.rs");
  const manifestBlock = buildSource.match(/const APP_COMMANDS: &\[&str\] = &\[([\s\S]*?)\];/);
  const manifest = manifestBlock ? [...manifestBlock[1].matchAll(/"([a-z_][a-z0-9_]*)"/g)].map((m) => m[1]) : [];
  check(
    registered.length > 0 && manifest.length > 0,
    `read ${registered.length} registered handlers and ${manifest.length} manifest commands`,
    "EXTRACTION FAILED: could not read generate_handler! or build.rs APP_COMMANDS"
  );
  const missingFromManifest = registered.filter((c) => !manifest.includes(c));
  const staleInManifest = manifest.filter((c) => !registered.includes(c));
  check(
    missingFromManifest.length === 0 && staleInManifest.length === 0,
    "build.rs APP_COMMANDS names exactly the generate_handler! commands",
    `APP MANIFEST DRIFT — not in build.rs: [${missingFromManifest.join(", ")}]; `
      + `not registered: [${staleInManifest.join(", ")}]`
  );
  // tauri-build writes one file per command into src-tauri/permissions/ and
  // never deletes one, and it reads every file under that directory whether or
  // not build.rs declares a manifest. So the directory is committed, and must
  // hold exactly the manifest: a stale file keeps a removed command grantable,
  // and a stray one left in a checkout of a branch without the manifest turns
  // on command gating that no capability grants.
  const permissionsDir = resolve(ROOT, "src-tauri/permissions");
  const autogeneratedDir = resolve(permissionsDir, "autogenerated");
  const topLevel = existsSync(permissionsDir) ? readdirSync(permissionsDir) : [];
  const generated = existsSync(autogeneratedDir)
    ? readdirSync(autogeneratedDir).map((name) => name.replace(/\.toml$/, ""))
    : [];
  const missingFiles = manifest.filter((c) => !generated.includes(c));
  const staleFiles = generated.filter((c) => !manifest.includes(c));
  check(
    topLevel.length === 1 && topLevel[0] === "autogenerated"
      && missingFiles.length === 0 && staleFiles.length === 0,
    "src-tauri/permissions/autogenerated holds exactly one file per APP_COMMANDS entry",
    `APP PERMISSION FILES DRIFT — src-tauri/permissions holds [${topLevel.join(", ")}]; `
      + `missing: [${missingFiles.join(", ")}]; stale: [${staleFiles.join(", ")}]. `
      + `Build once (tauri-build regenerates them), delete stale files, and commit the directory.`
  );
}

// The brief generic handler names MUST be gone.
const LEGACY_W4F_HANDLERS = [
  "create_zone",
  "update_zone",
  "delete_zone",
  "assign_channel_to_zone",
];
for (const fn of LEGACY_W4F_HANDLERS) {
  const re = new RegExp(`(^|[\\s,])${fn}([\\s,]|$)`, "m");
  check(
    !re.test(handlerListBlock),
    `legacy W4-F Rust handler "${fn}" removed from generate_handler! list`,
    `STILL PRESENT: legacy W4-F Rust handler "${fn}" — partial rename detected`
  );
}

// Name-level twin of the code checks. `sample_led_frame` was asserted present
// for four waves with no handler behind it; presence is not reachability.
console.log("\n[ Tauri command names — contracts ↔ generate_handler! parity ]");
// Empty, and worth keeping that way. `simulate_hue_fault` sat here while it had
// no frontend name at all; it is now declared as `HUE_DEBUG_COMMANDS` so the dev
// mock's passthrough set can be typed. The rule it was protecting — production
// code never invokes it — did not change, it moved to
// scripts/verify/mock-not-shipped.mjs, which fails on any reference under src/.
const UNCONTRACTED_RUST_COMMANDS = new Set([]);

const contractCommandNames = new Map();
for (const file of tsSourceFiles.filter((f) => f.includes("/shared/contracts/"))) {
  const src = stripComments(readFileSync(file, "utf-8"));
  for (const block of src.matchAll(/export const [A-Z0-9_]*COMMANDS\s*=\s*\{([\s\S]*?)\n\}/g)) {
    for (const entry of block[1].matchAll(/:\s*"([a-z][a-z0-9_]+)"/g)) {
      contractCommandNames.set(entry[1], file.split("/").pop());
    }
  }
}
const registeredHandlers = new Set(
  [...handlerListBlock.matchAll(/^\s*([a-z][a-z0-9_]+)\s*,/gm)].map((m) => m[1])
);

check(
  contractCommandNames.size > 0 && registeredHandlers.size > 0,
  `extracted ${contractCommandNames.size} contract command names / `
    + `${registeredHandlers.size} registered handlers`,
  "EXTRACTION FAILED: could not read command names from one or both sides"
);
for (const [name, file] of contractCommandNames) {
  check(
    registeredHandlers.has(name),
    `contract command "${name}" (${file}) is registered in generate_handler!`,
    `PHANTOM COMMAND "${name}" declared in ${file} but absent from generate_handler! — `
      + `invoke() would resolve to nothing. Delete the declaration or land the handler.`
  );
}
for (const name of registeredHandlers) {
  if (UNCONTRACTED_RUST_COMMANDS.has(name)) {
    note(`"${name}" registered with no contract name (allowlisted, debug-only)`);
    continue;
  }
  check(
    contractCommandNames.has(name),
    `registered handler "${name}" has a contract name`,
    `UNCONTRACTED COMMAND "${name}" is registered but no contract declares it — `
      + `add it to a *_COMMANDS map or to UNCONTRACTED_RUST_COMMANDS with a reason.`
  );
}
